const path = require('path');
const fs = require('fs');
const assert = require('node:assert/strict');
const { chromium } = require(path.join(process.env.TEMP, 'flood_portal_browser/node_modules/playwright'));

(async () => {
  const browser = await chromium.launch({executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless: true});
  const page = await browser.newPage({viewport: {width: 1500,height: 1100},deviceScaleFactor: 1});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => {if(message.type()==='error')errors.push(message.text());});
  const result = {};
  try {
    const response = await page.goto('http://127.0.0.1:8787/', {waitUntil:'networkidle'});
    assert.equal(response.status(),200);
    await page.waitForFunction(() => document.querySelector('#discharge-chart').data?.length >= 2);
    assert.equal(await page.locator('#overview-metrics .metric').count(),4);
    assert.equal(await page.locator('#load-error').isVisible(),false);
    await page.screenshot({path:'qa/overview-desktop.png',fullPage:true});
    result.overview_charts = await page.locator('#overview-view .js-plotly-plot').count();
    assert.equal(result.overview_charts,7);
    await page.selectOption('#year','2025');
    await page.waitForFunction(()=>document.querySelector('#from-date').value==='2025-01-01'&&document.querySelector('#discharge-chart').data[0].x.length===0);
    result.year_filter=true;
    await page.selectOption('#year','2024');
    await page.click('[data-case="flash"]');
    assert.equal(await page.locator('#empty-state').isVisible(),true);
    assert.equal(await page.locator('#populated').isVisible(),false);
    await page.click('#back-marala');
    await page.selectOption('#station','jassar');
    assert.match(await page.locator('#empty-state').innerText(),/Jassar/);
    await page.click('#back-marala');
    await page.selectOption('#horizon','long');
    assert.equal(await page.locator('#empty-state').isVisible(),true);
    await page.click('#back-marala');
    result.empty_cases_and_station=true;
    await page.click('[data-view="sources"]');
    await page.waitForSelector('#source-cards .source-card');
    assert.equal(await page.locator('#source-cards .source-card').count(),8);
    await page.fill('#source-search','NASA');
    assert.equal(await page.locator('#source-cards .source-card').count(),1);
    await page.fill('#source-search','');
    result.source_search=true;
    await page.screenshot({path:'qa/sources-desktop.png',fullPage:true});
    await page.click('[data-view="quality"]');
    await page.waitForSelector('#review-rows tr');
    assert.equal(await page.locator('#review-rows tr').count(),7);
    await page.fill('#integrity-search','GRAPH-DG');
    assert.equal(await page.locator('#integrity-ledger details').count(),1);
    await page.locator('#integrity-ledger summary').click();
    assert.match(await page.locator('#integrity-ledger').innerText(),/Actual SHA-256/);
    result.quality_and_ledger=true;
    await page.screenshot({path:'qa/quality-desktop.png',fullPage:true});
    await page.click('[data-view="catchment"]');
    await page.waitForFunction(()=>document.querySelector('#map-chart').data?.length>20);
    const withGrid=await page.evaluate(()=>document.querySelector('#map-chart').data.length);
    await page.uncheck('#show-grid');
    await page.waitForFunction(n=>document.querySelector('#map-chart').data.length<n,withGrid);
    await page.check('#show-grid');
    await page.waitForFunction(n=>document.querySelector('#map-chart').data.length===n,withGrid);
    result.catchment_interactions=true;
    await page.screenshot({path:'qa/catchment-desktop.png',fullPage:true});
    await page.click('[data-view="library"]');
    await page.click('[data-category="rainfall"]');
    await page.fill('#file-search','marala_catchment_daily_precipitation.csv');
    assert.equal(await page.locator('#file-rows tr').count(),1);
    const downloadPromise=page.waitForEvent('download');
    await page.locator('#file-rows a[download]').click();
    const download=await downloadPromise;
    assert.equal(download.suggestedFilename(),'marala_catchment_daily_precipitation.csv');
    result.download=true;
    await page.fill('#file-search','');
    await page.goto('http://127.0.0.1:8787/#overview',{waitUntil:'networkidle'});
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.querySelector('#discharge-chart').data?.length>=2);
    await page.waitForTimeout(500);
    const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
    assert.ok(width.scroll<=width.viewport+1,`Mobile horizontal overflow: ${JSON.stringify(width)}`);
    await page.click('#menu-toggle');
    assert.equal(await page.getAttribute('#menu-toggle','aria-expanded'),'true');
    await page.click('[data-case="urban"]');
    assert.equal(await page.locator('#empty-state').isVisible(),true);
    await page.click('#back-marala');
    await page.screenshot({path:'qa/overview-mobile.png',fullPage:true});
    result.mobile_layout_and_menu=true;
    assert.deepEqual(errors,[]);
    result.browser_errors=errors;
    fs.writeFileSync('qa/browser-report.json',JSON.stringify(result,null,2));
    console.log(JSON.stringify(result));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
